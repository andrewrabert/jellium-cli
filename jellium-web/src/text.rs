const TABLE_SOURCE: &str = include_str!("../strings/en-us.json");

/// The keys the boot shell reads straight from the table, which no variant
/// names: the shell runs before the wasm module exists.
#[cfg(test)]
const BOOT_KEYS: &[&str] = &["bootLoading", "bootWasmFailed", "bootRetry"];

/// Every key in the order the table writes it, which the parsed map does not
/// carry.
#[cfg(test)]
fn written() -> Vec<&'static str> {
    TABLE_SOURCE
        .lines()
        .filter_map(|line| line.trim_start().strip_prefix('"'))
        .filter_map(|line| line.split_once("\":"))
        .map(|(key, _)| key)
        .collect()
}

fn table() -> &'static serde_json::Map<String, serde_json::Value> {
    static TABLE: OnceLock<serde_json::Map<String, serde_json::Value>> = OnceLock::new();
    TABLE.get_or_init(|| {
        crate::failure::unraised::decoded(TABLE_SOURCE)
            .expect("strings/en-us.json is not a JSON object")
    })
}

/// The sentence `key` reads as; a key the table lacks reads as its own name,
/// which the gate is what prevents.
pub fn lookup(key: Text) -> &'static str {
    table()
        .get(key.key())
        .and_then(serde_json::Value::as_str)
        .unwrap_or_else(|| key.key())
}

pub fn format(key: Text, args: &[&str]) -> String {
    let template = lookup(key);
    let mut out = String::with_capacity(template.len());
    let mut rest = template;
    while let Some(open) = rest.find('{') {
        let Some(close) = rest[open..].find('}').map(|i| open + i) else {
            break;
        };
        let Ok(index) = rest[open + 1..close].parse::<usize>() else {
            out.push_str(&rest[..close + 1]);
            rest = &rest[close + 1..];
            continue;
        };
        out.push_str(&rest[..open]);
        out.push_str(args.get(index).copied().unwrap_or_default());
        rest = &rest[close + 1..];
    }
    out.push_str(rest);
    out
}

#[cfg(test)]
mod tests {
    use std::collections::HashSet;

    use wasm_bindgen_test::wasm_bindgen_test;

    use super::{BOOT_KEYS, Text, Wording, written};

    /// The table lists the boot shell's keys, then every variant's key in the
    /// order `text!` declares them, and nothing else.
    #[wasm_bindgen_test]
    fn the_table_holds_every_variant_in_declaration_order() {
        let expected: Vec<&str> = BOOT_KEYS
            .iter()
            .copied()
            .chain(Text::ALL.iter().map(|text| text.key()))
            .collect();
        let held = written();
        let named: HashSet<&str> = expected.iter().copied().collect();
        let carried: HashSet<&str> = held.iter().copied().collect();
        let mut missing: Vec<&str> = named.difference(&carried).copied().collect();
        let mut stray: Vec<&str> = carried.difference(&named).copied().collect();
        missing.sort_unstable();
        stray.sort_unstable();
        assert!(
            missing.is_empty() && stray.is_empty(),
            "the string table lacks {missing:?} and holds {stray:?} under no variant"
        );
        let misplaced = held
            .iter()
            .zip(&expected)
            .find(|(held, wanted)| held != wanted)
            .map(|(held, wanted)| format!("{held} stands where {wanted} belongs"));
        assert!(
            misplaced.is_none(),
            "the string table is out of declaration order: {misplaced:?}"
        );
    }

    /// A variant naming the reference's own key names it as the reference's own
    /// table spells it, which is what lets the key stand as a variant with no
    /// conversion between the two.
    #[wasm_bindgen_test]
    fn every_reference_key_is_spelled_as_the_reference_spells_it() {
        let held: Vec<String> = Text::ALL
            .iter()
            .filter_map(|text| match text.sentence() {
                Wording::Reference(key) => Some(format!("{key:?}")),
                Wording::Own => None,
            })
            .filter(|key| {
                !key.starts_with(|value: char| value.is_ascii_uppercase())
                    || !key.chars().all(|value| value.is_ascii_alphanumeric())
            })
            .collect();
        assert!(
            held.is_empty(),
            "keys the reference does not spell: {held:?}"
        );
    }
}
