use std::sync::OnceLock;

/// Declares the text enum, the roll the gate reads and the key each variant
/// reads under, from one list. A variant named here is in all three; a variant
/// named nowhere else does not exist.
macro_rules! text {
    ($($variant:ident => $key:literal,)*) => {
        #[derive(Debug, Clone, Copy, PartialEq, Eq)]
        pub enum Text {
            $($variant,)*
        }

        impl Text {
            /// Every variant, which is what the string table is checked
            /// against.
            #[cfg(test)]
            pub const ALL: &'static [Text] = &[$(Text::$variant,)*];

            /// The key this text reads under in the string table.
            pub fn key(self) -> &'static str {
                match self {
                    $(Text::$variant => $key,)*
                }
            }
        }
    };
}

