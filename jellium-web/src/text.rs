use std::sync::OnceLock;

#[cfg(test)]
use jellium_model::construct::Sentence;

/// Declares the text enum, the roll the gate reads and the key each variant
/// reads under, from one list. A variant named here is in all three; a variant
/// named nowhere else does not exist.
macro_rules! text {
    ($($variant:ident => $key:literal, $wording:expr,)*) => {
        #[derive(Debug, Clone, Copy, PartialEq, Eq)]
        pub enum Text {
            $($variant,)*
        }

        impl Text {
            /// Every variant, which is what the string table is checked
            /// against.
            #[cfg(test)]
            pub const ALL: &'static [Text] = &[$(Text::$variant,)*];

            /// The key this text reads under in the string table.
            pub fn key(self) -> &'static str {
                match self {
                    $(Text::$variant => $key,)*
                }
            }

            /// Read by the construct gate out of this file's own `text!`
            /// list, and by nothing at runtime, so it stands under
            /// `#[cfg(test)]` beside `ALL`, `BOOT_KEYS` and `written`.
            /// `cargo clippy --all-targets` and `cargo test` both build it, so
            /// every `Sentence` path in the list is type-checked on every run
            /// of the build.
            #[cfg(test)]
            pub fn sentence(self) -> Wording {
                match self {
                    $(Text::$variant => $wording,)*
                }
            }
        }
    };
}

/// Which key of the reference's own string table a sentence of this client
/// carries.
#[cfg(test)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Wording {
    /// The key `reference/constructs.tsv` gives the construct this sentence is
    /// drawn under.
    Reference(Sentence),
    /// No construct of that table keys this sentence. This is a fact about the
    /// table and not a claim that the sentence is this client's own; own-ness
    /// is asserted by a row of `reference/exemptions.tsv` and nowhere else.
    Unkeyed,
}

