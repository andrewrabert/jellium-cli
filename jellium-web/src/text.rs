const TABLE_SOURCE: &str = include_str!("../strings/en-us.json");

/// The keys the boot shell reads straight from the table, which no variant
/// names: the shell runs before the wasm module exists.
#[cfg(test)]
const BOOT_KEYS: &[&str] = &["bootLoading", "bootWasmFailed", "bootRetry"];

/// Every key in the order the table writes it, which the parsed map does not
/// carry.
#[cfg(test)]
fn written() -> Vec<&'static str> {
    TABLE_SOURCE
        .lines()
        .filter_map(|line| line.trim_start().strip_prefix('"'))
        .filter_map(|line| line.split_once("\":"))
        .map(|(key, _)| key)
        .collect()
}

fn table() -> &'static serde_json::Map<String, serde_json::Value> {
    static TABLE: OnceLock<serde_json::Map<String, serde_json::Value>> = OnceLock::new();
    TABLE.get_or_init(|| {
        crate::failure::unraised::decoded(TABLE_SOURCE)
            .expect("strings/en-us.json is not a JSON object")
    })
}

/// The sentence `key` reads as; a key the table lacks reads as its own name,
/// which the gate is what prevents.
pub fn lookup(key: Text) -> &'static str {
    table()
        .get(key.key())
        .and_then(serde_json::Value::as_str)
        .unwrap_or_else(|| key.key())
}

pub fn format(key: Text, args: &[&str]) -> String {
    let template = lookup(key);
    let mut out = String::with_capacity(template.len());
    let mut rest = template;
    while let Some(open) = rest.find('{') {
        let Some(close) = rest[open..].find('}').map(|i| open + i) else {
            break;
        };
        let Ok(index) = rest[open + 1..close].parse::<usize>() else {
            out.push_str(&rest[..close + 1]);
            rest = &rest[close + 1..];
            continue;
        };
        out.push_str(&rest[..open]);
        out.push_str(args.get(index).copied().unwrap_or_default());
        rest = &rest[close + 1..];
    }
    out.push_str(rest);
    out
}

