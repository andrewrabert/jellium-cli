use jellium_model::construct::Sentence;

/// Declares the text enum, the roll the gate reads and the key each variant
/// reads under, from one list. A variant named here is in all three; a variant
/// named nowhere else does not exist.
macro_rules! text {
    ($($variant:ident => $key:literal, $wording:expr,)*) => {
        #[derive(Debug, Clone, Copy, PartialEq, Eq)]
        pub enum Text {
            $($variant,)*
        }

        impl Text {
            /// Every variant, which is what the string table is checked
            /// against.
            #[cfg(test)]
            pub const ALL: &'static [Text] = &[$(Text::$variant,)*];

            /// The key this text reads under in the string table.
            pub fn key(self) -> &'static str {
                match self {
                    $(Text::$variant => $key,)*
                }
            }

            /// What this sentence stands for, which is what the construct gate
            /// compares against the reference's own key.
            #[cfg(test)]
            pub fn sentence(self) -> Wording {
                match self {
                    $(Text::$variant => $wording,)*
                }
            }
        }
    };
}

